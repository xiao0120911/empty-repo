// Offline rendering regression: real summary parser from App.vue, no browser or mock login.
const fs = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')
const { createSSRApp, h, defineComponent, computed } = require('vue')
const { renderToString } = require('@vue/server-renderer')
const ts = require('typescript')
const source = fs.readFileSync(path.join(__dirname, 'src/App.vue'), 'utf8')
const start = source.indexOf('const legacyReportNotice=')
const end = source.indexOf('const date=', start)
assert(start >= 0 && end > start)
const js = ts.transpileModule(source.slice(start, end), { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS } }).outputText
const component = new Function('h', 'defineComponent', 'computed', js + '\nreturn ReportSummary')(h, defineComponent, computed)
const render = text => renderToString(createSSRApp({ render: () => h(component, { text }) }))
async function main() {
  const summary = await render('# 任务结果总结\n\n已找到事件 **9300000000000001602**。\n\n## 预警详情\n1. 单位：测试食堂；状态：待反馈\n2. 更新时间：2026-10-19\n\n| 场景 | 摄像头编号 |\n| --- | --- |\n| 加工烹饪 | CAM001 |')
  assert(summary.includes('<h1>任务结果总结</h1>'))
  assert(summary.includes('<strong>9300000000000001602</strong>'))
  assert(summary.includes('<ol') && summary.includes('<table>') && summary.includes('CAM001'))
  const cited = await render('查询事件 [9300000000000001602]，依据 [2]：状态为待反馈。')
  assert(cited.includes('9300000000000001602') && cited.includes('待反馈') && !cited.includes('历史结构化'))
  const unsafe = await render('结果文本 <img src=x onerror=alert(1)>')
  assert(!unsafe.includes('<img') && unsafe.includes('&lt;img'))
  const raw = await render('{"code":0,"data":{"id":"9300000000000001602"}}')
  assert(!raw.includes('"code"') && raw.includes('历史结构化'))
  const code = await render('# 总结\n有效业务结论。\n```json\n{"password":"secret"}\n```')
  assert(!code.includes('password') && code.includes('有效业务结论'))
  const template = source.slice(source.indexOf('<template>'))
  assert(!template.includes('conversation-panel') && !template.includes('conversation-history'))
  assert(!template.includes('轮任务') && !template.includes('提交下一轮') && !template.includes('第 {{i+1}} 轮'))
  assert(template.includes('任务记录') && template.includes('总结结果') && template.includes('@click="newConversation"'))
  assert(template.includes('active.result.display_report ?? active.result.report'))
  assert(template.includes('<details><summary>查看脱敏证据与哈希</summary>'))
  assert(source.includes('conversation_id:cid') && source.includes('await refreshAll(true)'))
  console.log(JSON.stringify({ summary_render: 'passed', headings_lists_tables: 'passed', large_id: 'passed', html_escaped: 'passed', raw_json_hidden: 'passed', code_fence_hidden: 'passed', old_layout_restored: 'passed', context_preserved: 'passed', audit_details_preserved: 'passed', browser_e2e: 'not executed' }, null, 2))
}
main().catch(error => { console.error(error); process.exitCode = 1 })
